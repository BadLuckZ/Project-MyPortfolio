import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { projects } from "../../js/projects/project.js";
import { experiences } from "../../js/experiences/experience.js";
import { formatPeriod } from "../../js/formatPeriod.js";
import { htmlToText } from "./html2text.ts";

const SITE_URL = "https://thanagorn.com/";
const ASSISTANT_DIR = path.resolve(import.meta.dirname, "..");
const ABOUT_PATH = path.join(ASSISTANT_DIR, "data", "about.md");
const OUTPUT_PATH = path.join(ASSISTANT_DIR, "generated", "profile.md");

interface Entry {
  id: string;
  title: string;
  subtitle: string;
  org?: string;
  type: string;
  start_month: number;
  start_year: number;
  end_month: number | null;
  end_year: number | null;
  information: string;
  learn: string;
  contribution: string;
  github: string;
  preview_demo: string;
  have_doc: boolean;
  doc_type: string;
  preview_doc: string;
}

function toAbsolutePath(url: string): string {
  return new URL(url, SITE_URL).href;
}

function toText(
  entry: Entry,
  field: "information" | "learn" | "contribution",
): string {
  try {
    return htmlToText(entry[field]);
  } catch (err) {
    throw new Error(`${entry.id}.${field}: ${(err as Error).message}`, {
      cause: err,
    });
  }
}

function renderEntry(entry: Entry): string {
  const docLabel = entry.doc_type === "article" ? "Article" : "Document";
  const facts: Array<[string, string | undefined]> = [
    ["Organization", entry.org],
    ["Role", entry.subtitle],
    ["Type", entry.type],
    ["Period", formatPeriod(entry)],
    ["GitHub", entry.github],
    ["Demo", entry.preview_demo],
    [docLabel, entry.have_doc ? toAbsolutePath(entry.preview_doc) : undefined],
  ];

  const lines = [`## ${entry.title}`];
  for (const [label, value] of facts) {
    if (value) lines.push(`- ${label}: ${value}`);
  }

  const sections = [
    ["Information", toText(entry, "information")],
    ["What I learned", toText(entry, "learn")],
    ["Contribution", toText(entry, "contribution")],
  ];
  for (const [heading, text] of sections) {
    if (text) lines.push("", `### ${heading}`, text);
  }
  return lines.join("\n");
}

const about = (await readFile(ABOUT_PATH, "utf8")).trim();
const output =
  [
    "<!-- Generated by scripts/build-profile.ts -->",
    about,
    "# Experiences",
    ...(experiences as Entry[]).map(renderEntry),
    "# Projects",
    ...(projects as Entry[]).map(renderEntry),
  ].join("\n\n") + "\n";

await mkdir(path.dirname(OUTPUT_PATH), { recursive: true });
await writeFile(OUTPUT_PATH, output, "utf8");
console.log(
  `Generate profile.md with (${experiences.length} experiences, ${projects.length} projects)`,
);
